#!/usr/bin/env bash
# Manage scheduled Claude jobs: list them, run one by hand, install or
# remove the systemd timer that fires it.
#
#   claude-jobs list
#   claude-jobs show <name>
#   claude-jobs run <name> [--dry-run]
#   claude-jobs install <name>
#   claude-jobs uninstall <name>
#
# The spec file is the source of truth. `install` reads SCHEDULE from it and
# writes the timer unit, because systemd cannot read OnCalendar from an
# EnvironmentFile.
set -euo pipefail

umask 077

JOBS_CONFIG_DIR="${CLAUDE_JOBS_CONFIG_DIR:-$HOME/.config/claude-jobs}"
SYSTEMD_USER_DIR="${SYSTEMD_USER_DIR:-$HOME/.config/systemd/user}"
LIB_DIR="${CLAUDE_JOBS_LIB_DIR:-$HOME/.local/lib/claude-jobs}"
RUNNER="$LIB_DIR/claude-job-run.sh"

usage() {
    sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
}

spec_file() {
    local name="$1"
    local path="$JOBS_CONFIG_DIR/$name.job"
    [[ -r "$path" ]] || { echo "No spec for job '$name' at $path" >&2; exit 2; }
    printf '%s' "$path"
}

# Read one key from a spec without sourcing it into this shell.
spec_value() {
    local path="$1" key="$2"
    ( set -euo pipefail
      # shellcheck disable=SC1090
      source "$path"
      printf '%s' "${!key:-}" )
}

cmd_list() {
    shopt -s nullglob
    local any=0
    printf '%-28s %-8s %s\n' "JOB" "ENABLED" "SCHEDULE"
    for path in "$JOBS_CONFIG_DIR"/*.job; do
        any=1
        local name enabled schedule timer_state
        name="$(basename "$path" .job)"
        enabled="$(spec_value "$path" ENABLED)"
        schedule="$(spec_value "$path" SCHEDULE)"
        timer_state="not installed"
        if [[ -f "$SYSTEMD_USER_DIR/claude-job@$name.timer" ]]; then
            timer_state="installed"
        fi
        printf '%-28s %-8s %s  (%s)\n' "$name" "${enabled:-1}" "${schedule:-none}" "$timer_state"
    done
    [[ "$any" == 1 ]] || echo "No job specs in $JOBS_CONFIG_DIR"
}

cmd_show() {
    local name="${1:-}"; [[ -n "$name" ]] || usage
    cat "$(spec_file "$name")"
}

cmd_run() {
    local name="${1:-}"; [[ -n "$name" ]] || usage
    shift || true
    [[ -x "$RUNNER" ]] || { echo "Runner is not installed at $RUNNER" >&2; exit 1; }
    "$RUNNER" "$name" "$@"
}

cmd_install() {
    local name="${1:-}"; [[ -n "$name" ]] || usage
    local path schedule description
    path="$(spec_file "$name")"
    schedule="$(spec_value "$path" SCHEDULE)"
    description="$(spec_value "$path" DESCRIPTION)"
    [[ -n "$schedule" ]] || { echo "Spec has no SCHEDULE: $path" >&2; exit 1; }

    mkdir -p "$SYSTEMD_USER_DIR"
    local timer="$SYSTEMD_USER_DIR/claude-job@$name.timer"
    cat >"$timer" <<EOF
# Generated by claude-jobs install from $path
# Edit SCHEDULE in the spec and re-run install; do not edit this file.
[Unit]
Description=${description:-Scheduled Claude job: $name}

[Timer]
OnCalendar=$schedule
Persistent=true
AccuracySec=1min
Unit=claude-job@$name.service

[Install]
WantedBy=timers.target
EOF

    systemctl --user daemon-reload
    systemctl --user enable --now "claude-job@$name.timer"
    echo "Installed claude-job@$name.timer  OnCalendar=$schedule"
    systemctl --user list-timers --all --no-pager "claude-job@$name.timer" | head -3
}

cmd_uninstall() {
    local name="${1:-}"; [[ -n "$name" ]] || usage
    systemctl --user disable --now "claude-job@$name.timer" 2>/dev/null || true
    rm -f "$SYSTEMD_USER_DIR/claude-job@$name.timer"
    systemctl --user daemon-reload
    echo "Removed claude-job@$name.timer  (the spec in $JOBS_CONFIG_DIR is untouched)"
}

case "${1:-}" in
    list) shift; cmd_list "$@" ;;
    show) shift; cmd_show "$@" ;;
    run) shift; cmd_run "$@" ;;
    install) shift; cmd_install "$@" ;;
    uninstall) shift; cmd_uninstall "$@" ;;
    *) usage ;;
esac
